    <script>
        /* =========================================================
   JAKARTA FILM COMMISSION - MEMBERSHIP PAGE
   FAQ ACCORDION
========================================================= */

document.addEventListener("DOMContentLoaded", function () {

    const faqItems =
        document.querySelectorAll(".faq-item");

    if (!faqItems.length) {
        return;
    }

    faqItems.forEach(function (item) {

        const question =
            item.querySelector(".faq-question");

        const answer =
            item.querySelector(".faq-answer");

        if (!question || !answer) {
            return;
        }

        question.addEventListener("click", function () {

            const isOpen =
                item.classList.contains("open");

            /*
            | Tutup semua FAQ lain dulu (accordion style -
            | cuma satu yang terbuka dalam satu waktu).
            */
            faqItems.forEach(function (otherItem) {

                otherItem.classList.remove("open");

                const otherAnswer =
                    otherItem.querySelector(".faq-answer");

                if (otherAnswer) {
                    otherAnswer.style.maxHeight = null;
                }

            });

            /*
            | Kalau yang diklik sebelumnya sudah terbuka,
            | biarkan tertutup (toggle). Kalau belum, buka.
            */
            if (!isOpen) {

                item.classList.add("open");
                answer.style.maxHeight = answer.scrollHeight + "px";

            }

        });

    });

});
    </script>
